#!/usr/bin/env python3
"""
Дикторський текст: готує репліки з src/config.ts (NARRATION_LINES).

  npm run narration                 # згенерувати всі репліки
  npm run narration -- --force      # перегенерувати навіть ті, що вже є

Для кожної репліки <id>:
  1. якщо є ваш запис recordings/<id>.(m4a|mp3|wav|ogg|aac|flac|webm) — береться він;
  2. інакше — синтез голосом NARRATOR.voice (Microsoft Neural TTS через edge-tts,
     потрібен інтернет і `pip install edge-tts`).
Далі: обрізання тиші на початку/в кінці, вирівнювання гучності (-14 LUFS,
true peak -2 dB) -> public/voice/narration/<id>.mp3, тривалості -> src/narration-manifest.ts,
і перегенерація синтезованої музики під новий таймлайн (сцени подовжуються під голос).
"""
import asyncio
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "public", "voice", "narration")
REC_DIR = os.path.join(ROOT, "recordings")
MANIFEST = os.path.join(ROOT, "src", "narration-manifest.ts")
EXTS = (".m4a", ".mp3", ".wav", ".ogg", ".aac", ".flac", ".webm", ".opus")

FILTER = (
    "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.05,"
    "areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.08,areverse,"
    "loudnorm=I=-14:TP=-2:LRA=9,"
    "afade=t=in:d=0.015,areverse,afade=t=in:d=0.04,areverse"
)


def timeline():
    out = subprocess.run(["node", os.path.join(ROOT, "scripts", "export-timeline.mts")],
                         capture_output=True, text=True, check=True, cwd=ROOT)
    return json.loads(out.stdout)


def find_recording(line_id):
    if not os.path.isdir(REC_DIR):
        return None
    for name in os.listdir(REC_DIR):
        base, ext = os.path.splitext(name)
        if base == line_id and ext.lower() in EXTS:
            return os.path.join(REC_DIR, name)
    return None


async def synth(text, path, narrator):
    try:
        import edge_tts
    except ImportError:
        sys.exit("Потрібен edge-tts: pip install edge-tts (або покладіть свої записи в recordings/)")
    proxy = os.environ.get("HTTPS_PROXY") or os.environ.get("https_proxy")
    com = edge_tts.Communicate(text, narrator["voice"], rate=narrator["rate"], pitch=narrator["pitch"],
                               proxy=proxy)
    await com.save(path)


def process(src, dst):
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-vn", "-ac", "1", "-ar", "48000",
                    "-af", FILTER, "-ar", "48000", "-b:a", "192k", dst], check=True)
    d = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", dst],
                       capture_output=True, text=True, check=True).stdout.strip()
    return float(d)


def write_manifest(entries, ids):
    lines = [
        "// AUTO-GENERATED by scripts/narration.py — do not edit by hand.",
        "import type {NarrationId} from './config.ts';",
        "",
        "export type NarrationClip = {file: string; durationSec: number} | null;",
        "",
        "export const narrationManifest: Record<NarrationId, NarrationClip> = {",
    ]
    for i in ids:
        e = entries.get(i)
        val = f"{{file: 'voice/narration/{i}.mp3', durationSec: {e:.3f}}}" if e else "null"
        lines.append(f"  '{i}': {val},")
    lines += ["};", ""]
    open(MANIFEST, "w").write("\n".join(lines))


def main():
    force = "--force" in sys.argv
    tl = timeline()
    os.makedirs(OUT_DIR, exist_ok=True)
    entries = {}
    ids = [l["id"] for l in tl["narration"]]
    for line in tl["narration"]:
        lid, text = line["id"], line["say"]
        dst = os.path.join(OUT_DIR, f"{lid}.mp3")
        rec = find_recording(lid)
        with tempfile.TemporaryDirectory() as tmp:
            if rec:
                src, how = rec, f"ваш запис {os.path.relpath(rec, ROOT)}"
            elif os.path.exists(dst) and not force:
                d = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                                          "-of", "csv=p=0", dst], capture_output=True, text=True).stdout)
                entries[lid] = d
                print(f"  {lid:26s} {d:5.2f} с  (вже є)")
                continue
            else:
                src = os.path.join(tmp, "tts.mp3")
                asyncio.run(synth(text, src, tl["narrator"]))
                how = f"TTS {tl['narrator']['voice']}"
            entries[lid] = process(src, dst)
        print(f"  {lid:26s} {entries[lid]:5.2f} с  ← {how}: «{text}»")
    write_manifest(entries, ids)
    # таймлайн змінився -> музика під нові межі сцен (ваш власний music.mp3 не чіпається)
    subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "generate_audio.py"), "--music-only"], check=True)
    tl = timeline()
    print(f"Тривалість відео: {tl['totalFrames'] / tl['fps']:.1f} с")


if __name__ == "__main__":
    main()
