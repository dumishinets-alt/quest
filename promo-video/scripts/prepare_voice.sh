#!/usr/bin/env bash
# Підготовка голосових записів:
#   npm run voice                                   # шукає «audio 1.*» і «audio 2.*» у Downloads / Завантаження
#   npm run voice -- "/шлях/audio 1.m4a" "/шлях/audio 2.m4a"
#
# Що робить: копіює в public/voice/ як voice1.mp3 і voice2.mp3, обрізає тишу
# на початку й у кінці, вирівнює гучність (EBU R128, -16 LUFS, true peak -1.5 dB),
# записує тривалості в src/voice-manifest.ts (сцени 1 і 6 подовжуються під голос)
# і перегенеровує синтезовану музику під новий таймлайн.
set -euo pipefail
cd "$(dirname "$0")/.."

find_input() {
  local n="$1"
  for dir in "$HOME/Downloads" "$HOME/Завантаження" "$HOME/Загрузки"; do
    [ -d "$dir" ] || continue
    local f
    f=$(find "$dir" -maxdepth 1 -type f \( -iname "audio ${n}.*" -o -iname "audio${n}.*" -o -iname "audio_${n}.*" \) | head -n 1)
    if [ -n "$f" ]; then echo "$f"; return 0; fi
  done
  return 1
}

IN1="${1:-$(find_input 1 || true)}"
IN2="${2:-$(find_input 2 || true)}"

mkdir -p public/voice

process() {
  local in="$1" out="$2"
  # тиша: поріг -45 dB; обрізаємо спереду, перевертаємо, обрізаємо «спереду» (тобто кінець), перевертаємо назад
  ffmpeg -y -loglevel error -i "$in" -vn -ac 1 -ar 48000 \
    -af "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.08,areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.12,areverse,loudnorm=I=-16:TP=-1.5:LRA=11,afade=t=in:d=0.02,areverse,afade=t=in:d=0.04,areverse" \
    -ar 48000 -b:a 192k "$out"
  ffprobe -v error -show_entries format=duration -of csv=p=0 "$out"
}

D1=null
D2=null
if [ -n "$IN1" ] && [ -f "$IN1" ]; then
  d=$(process "$IN1" public/voice/voice1.mp3)
  D1="{file: 'voice/voice1.mp3', durationSec: $d}"
  echo "voice1: $IN1 -> public/voice/voice1.mp3 (${d} с)"
else
  echo "voice1: файл «audio 1» не знайдено — сцена 1 буде без голосу"
fi
if [ -n "$IN2" ] && [ -f "$IN2" ]; then
  d=$(process "$IN2" public/voice/voice2.mp3)
  D2="{file: 'voice/voice2.mp3', durationSec: $d}"
  echo "voice2: $IN2 -> public/voice/voice2.mp3 (${d} с)"
else
  echo "voice2: файл «audio 2» не знайдено — сцена 6 буде без голосу"
fi

cat > src/voice-manifest.ts <<EOF
// AUTO-GENERATED by scripts/prepare_voice.sh — do not edit by hand.
// durationSec: тривалість обробленого запису (після обрізання тиші).
export type VoiceClip = {file: string; durationSec: number} | null;

export const voiceManifest: {voice1: VoiceClip; voice2: VoiceClip} = {
  voice1: ${D1},
  voice2: ${D2},
};
EOF

# музика під новий таймлайн (ваш власний public/music.mp3 не чіпається)
python3 scripts/generate_audio.py --music-only
node scripts/export-timeline.mts | head -n 30
